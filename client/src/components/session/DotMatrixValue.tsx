export interface DotMatrixValueProps {
  value: string;
  ariaLabel?: string;
  className?: string;
  style?: React.CSSProperties;
}

export function DotMatrixValue({
  value,
  ariaLabel,
  className,
  style,
}: DotMatrixValueProps) {
  const normalized = (value || "0").toUpperCase();
  const step = 6;
  const r = 2.28;
  let colOffset = 0;
  const circles: Array<{ cx: string; cy: string }> = [];

  for (let idx = 0; idx < normalized.length; idx++) {
    const ch = normalized[idx];
    const glyph = GLYPHS[ch] ?? GLYPHS["0"];
    const w = glyph[0].length;
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < w; col++) {
        if (glyph[row][col] === "#") {
          circles.push({
            cx: ((colOffset + col + 0.5) * step).toFixed(1),
            cy: ((row + 0.5) * step).toFixed(1),
          });
        }
      }
    }
    colOffset += w;
    if (idx < normalized.length - 1) {
      colOffset += 1;
    }
  }

  const width = Math.max(step, colOffset * step);
  const height = 7 * step;

  return (
    <svg
      role="img"
      aria-label={ariaLabel ?? value}
      width={width}
      height={height}
      viewBox={`0 0 ${width.toFixed(1)} ${height.toFixed(1)}`}
      fill="currentColor"
      className={className}
      style={{ display: "block", overflow: "visible", ...style }}
    >
      {circles.map((c, i) => (
        <circle key={i} cx={c.cx} cy={c.cy} r={r} />
      ))}
    </svg>
  );
}

export default DotMatrixValue;
